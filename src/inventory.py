"""
PHARMORA - Inventory Risk Engine (Phase 3: Operational Intelligence)
====================================================================
Implements dual inventory risk intelligence:
1. Feature 1: Stockout Risk Detection
   - Inventory Position = Current Stock + Pending Order Quantity
   - Lead-Time Demand = Expected demand during supplier replenishment lead time
     (derived from 7-day machine-learning forecasts and historical averages)
   - Reorder Point (ROP) = Lead-Time Demand + Statistical Safety Stock
   - Risk Status: CRITICAL_STOCKOUT_RISK, REORDER_WARNING, HEALTHY, OVERSTOCKED
   - Estimated Days of Cover (zero-division safe)
2. Feature 2: FEFO Expiry Risk Detection
   - First-Expired, First-Out (FEFO) cumulative demand allocation
   - Prevents double-counting demand across sequential batches
   - Distinct classification of EXPIRED vs. EXPIRY_RISK vs. HEALTHY_BATCH
   - Calculates unsold units at risk and inventory value at risk (₹)
   - Zero-tolerance medical safety: Never recommends selling expired medicines.
3. Backward Compatibility:
   - Preserves calculate_inventory_metrics() and assess_stock_status() for app.py.
"""

