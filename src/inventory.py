# Master Execution Pipeline & Output Persistence
# ---------------------------------------------------------------------------
def run_inventory_pipeline(
    inventory_path: str = "data/inventory.csv",
    batches_path: str = "data/batches.csv",
    forecast_path: str = "processed/forecast_7days.parquet",
    sales_path: str = "processed/daily_sales.parquet",
    output_dir: str = "processed",
    reference_date: str = DEFAULT_REFERENCE_DATE
) -> Dict[str, Any]:
    """
    Executes the complete Phase 3 Inventory Risk Pipeline:
    1. Ingests or generates synthetic inventory and batch datasets.
    2. Ingests 7-day machine-learning demand forecasts.
    3. Runs Stockout Risk Detection across all 8 medicine categories.
    4. Runs FEFO Expiry Risk Detection across all batches.
    5. Persists curated output tables to processed/ (Parquet and CSV).
    6. Formats and prints operational intelligence summaries.
    """
    inv_file = Path(inventory_path)
    batch_file = Path(batches_path)
    fc_file = Path(forecast_path)
    sales_file = Path(sales_path)
    out_dir = Path(output_dir)

    out_dir.mkdir(parents=True, exist_ok=True)

    print("=" * 80)
    print("  PHARMORA - PHASE 3: INVENTORY RISK ENGINE (STOCKOUT & EXPIRY)")
    print("=" * 80)
    print(f" -> Reference Date for Evaluation: {reference_date}")

    # Generate synthetic datasets if not present
    if not inv_file.exists() or not batch_file.exists():
        print(" -> [NOTICE] Inventory / batch CSVs not found. Generating reproducible synthetic datasets...")
        generate_synthetic_inventory_data(output_dir="data", seed=42)

    inv_df = pd.read_csv(inv_file)
    batch_df = pd.read_csv(batch_file)
    print(f" -> Ingested Inventory Records: {len(inv_df)} medicines from {inv_file.as_posix()}")
    print(f" -> Ingested Batch Records:     {len(batch_df)} batches from {batch_file.as_posix()}")

    forecast_df = _read_parquet_or_csv(fc_file) if fc_file.exists() else None
    sales_df = _read_parquet_or_csv(sales_file) if sales_file.exists() else None

    # -----------------------------------------------------------------------
    # 1. Stockout Risk Analysis
    # -----------------------------------------------------------------------
    print("\n" + "-" * 80)
    print(" [1/2] RUNNING STOCKOUT RISK DETECTION (INVENTORY POSITION VS. ROP)")
    print("-" * 80)
    stockout_results = detect_stockout_risk(
        inventory_df=inv_df,
        forecast_df=forecast_df,
        sales_df=sales_df
    )

    display_stockout = stockout_results[[
        "medicine_id", "current_stock", "pending_order_quantity", "inventory_position",
        "supplier_lead_time_days", "lead_time_demand", "reorder_point",
        "estimated_days_of_cover", "risk_status"
    ]].copy()
    display_stockout.columns = [
        "Medicine", "Stock", "Pending", "Inv.Pos",
        "Lead(d)", "LT Dem.", "ROP", "Cover(d)", "Risk Status"
    ]
    print(display_stockout.to_string(index=False))

    # Summary Counts
    crit_count = (stockout_results["risk_status"] == "CRITICAL_STOCKOUT_RISK").sum()
    warn_count = (stockout_results["risk_status"] == "REORDER_WARNING").sum()
    hlth_count = (stockout_results["risk_status"] == "HEALTHY").sum()
    over_count = (stockout_results["risk_status"] == "OVERSTOCKED").sum()
    print(f"\n -> Stockout Risk Summary: {crit_count} Critical | {warn_count} Warning | {hlth_count} Healthy | {over_count} Overstocked")

    # -----------------------------------------------------------------------
    # 2. Expiry Risk Analysis
    # -----------------------------------------------------------------------
    print("\n" + "-" * 80)
    print(" [2/2] RUNNING FEFO EXPIRY RISK DETECTION (CUMULATIVE DEMAND ALLOCATION)")
    print("-" * 80)
    expiry_results = detect_expiry_risk(
        batches_df=batch_df,
        forecast_df=forecast_df,
        sales_df=sales_df,
        reference_date=reference_date
    )

    display_expiry = expiry_results[[
        "batch_id", "medicine_id", "batch_quantity", "expiry_date",
        "days_until_expiry", "expected_demand_before_expiry",
        "unsold_units_at_risk", "value_at_risk", "expiry_status"
    ]].copy()
    display_expiry.columns = [
        "Batch ID", "Med", "Qty", "Expiry", "Days",
        "Exp.Dem", "Unsold", "Val@Risk(₹)", "Status"
    ]
    print(display_expiry.to_string(index=False))

    expired_count = (expiry_results["expiry_status"] == "EXPIRED").sum()
    near_risk_count = (expiry_results["expiry_status"] == "EXPIRY_RISK").sum()
    safe_count = (expiry_results["expiry_status"] == "HEALTHY_BATCH").sum()
    total_val_at_risk = expiry_results["value_at_risk"].sum()
    expired_val = expiry_results[expiry_results["expiry_status"] == "EXPIRED"]["value_at_risk"].sum()
    near_val = expiry_results[expiry_results["expiry_status"] == "EXPIRY_RISK"]["value_at_risk"].sum()

    print(f"\n -> Expiry Risk Summary: {expired_count} Expired (₹{expired_val:,.2f}) | {near_risk_count} Near Expiry Risk (₹{near_val:,.2f}) | {safe_count} Healthy Batches")
    print(f" -> Total Capital at Risk: ₹{total_val_at_risk:,.2f}")

    # -----------------------------------------------------------------------
    # Output Persistence
    # -----------------------------------------------------------------------
    stockout_parquet = out_dir / "inventory_stockout_risk.parquet"
    stockout_csv = out_dir / "inventory_stockout_risk.csv"
    expiry_parquet = out_dir / "batch_expiry_risk.parquet"
    expiry_csv = out_dir / "batch_expiry_risk.csv"

    stockout_results.to_parquet(stockout_parquet, index=False)
    stockout_results.to_csv(stockout_csv, index=False)
    expiry_results.to_parquet(expiry_parquet, index=False)
    expiry_results.to_csv(expiry_csv, index=False)

    print("\n" + "=" * 80)
    print("  INVENTORY PIPELINE COMPLETED SUCCESSFULLY!")
    print(f"  -> Stockout Table Saved: {stockout_parquet.as_posix()} ({len(stockout_results)} rows)")
    print(f"  -> Expiry Table Saved:   {expiry_parquet.as_posix()} ({len(expiry_results)} rows)")
