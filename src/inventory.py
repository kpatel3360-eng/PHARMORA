# Feature 2: FEFO Expiry Risk Detection Engine
# ---------------------------------------------------------------------------
def detect_expiry_risk(
    batches_df: pd.DataFrame,
    forecast_df: Optional[pd.DataFrame] = None,
    sales_df: Optional[pd.DataFrame] = None,
    reference_date: str = DEFAULT_REFERENCE_DATE
) -> pd.DataFrame:
    """
    Evaluates expiration vulnerability across pharmaceutical batches:
    - Incorporates First-Expired, First-Out (FEFO) dispensing logic.
    - Prevents double-counting demand by deducting quantities absorbed by earlier-expiring batches.
    - Accurately segregates EXPIRED batches from near-term EXPIRY_RISK batches.
    - Strict Healthcare Safety Rule: Never recommends selling expired medication.
    - Computes unsold units at risk and inventory capital at risk (₹).
    """
    df = batches_df.copy()
    ref_dt = pd.to_datetime(reference_date)

    required_cols = ["batch_id", "medicine_id", "batch_quantity", "expiry_date", "unit_cost"]
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in batch dataset: {missing_cols}")

    # Coerce types and clean dates
    df["batch_id"] = df["batch_id"].astype(str)
    df["medicine_id"] = df["medicine_id"].astype(str)
    df["batch_quantity"] = pd.to_numeric(df["batch_quantity"], errors="coerce").fillna(0.0).clip(lower=0.0)
    df["expiry_date"] = pd.to_datetime(df["expiry_date"], errors="coerce")
    df["unit_cost"] = pd.to_numeric(df["unit_cost"], errors="coerce").fillna(0.0).clip(lower=0.0)

    # Drop invalid rows
    df = df.dropna(subset=["expiry_date"])
    df = df[df["medicine_id"].isin(VALID_MEDICINE_IDS)].copy()

    # Daily forecast lookup
    fc_dict = {}
    if forecast_df is not None and not forecast_df.empty:
        fc_clean = forecast_df.copy()
        fc_clean["forecast_date"] = pd.to_datetime(fc_clean["forecast_date"])
        for med, group in fc_clean.groupby("medicine_id"):
            fc_dict[med] = group.sort_values("forecast_date")["predicted_units"].tolist()

    # Historical demand fallback
    hist_avg_demand = {}
    if sales_df is not None and not sales_df.empty:
        hist_avg_demand = sales_df.groupby("medicine_id")["units_sold"].mean().to_dict()

    batch_results = []

    # Process each drug category independently under FEFO queue
    for med in sorted(df["medicine_id"].unique()):
        med_batches = df[df["medicine_id"] == med].sort_values(
            by=["expiry_date", "batch_id"]
        ).reset_index(drop=True)

        daily_fc = fc_dict.get(med, [])
        fc_len = len(daily_fc)
        hist_mean = hist_avg_demand.get(med, 5.0)

        # Cumulative quantity of earlier unexpired batches that have priority claim on future demand
        prior_unexpired_cumulative_qty = 0.0

        for _, b_row in med_batches.iterrows():
            b_id = b_row["batch_id"]
            b_qty = float(b_row["batch_quantity"])
            exp_date = b_row["expiry_date"]
            cost = float(b_row["unit_cost"])

            days_until_exp = int((exp_date - ref_dt).days)

            # Scenario A: ALREADY EXPIRED BATCH
            if days_until_exp <= 0:
                expiry_status = "EXPIRED"
                exp_demand_cumulative = 0.0
                prior_qty_deducted = 0.0
                net_demand_allocated = 0.0
                unsold_units = b_qty
                val_at_risk = round(unsold_units * cost, 2)
                rec = "DO NOT SELL: Expired medicine. Quarantine immediately for authorized medical destruction."

            # Scenario B: ACTIVE / UNEXPIRED BATCH (FEFO Demand Modeling)
            else:
                # 1. Total cumulative demand expected from ref_dt up to this batch's expiration date
                if days_until_exp <= fc_len:
                    exp_demand_cumulative = float(sum(daily_fc[:days_until_exp]))
                else:
                    exp_demand_cumulative = float(
                        sum(daily_fc) + (days_until_exp - fc_len) * hist_mean
                    )

                # 2. Demand available for THIS batch after earlier-expiring batches absorb their share
                prior_qty_deducted = prior_unexpired_cumulative_qty
                available_demand = max(0.0, exp_demand_cumulative - prior_qty_deducted)

                # 3. Units absorbed and residual unsold units
                units_absorbed = min(b_qty, available_demand)
                unsold_units = round(max(0.0, b_qty - units_absorbed), 2)
                val_at_risk = round(unsold_units * cost, 2)
                net_demand_allocated = round(units_absorbed, 2)

                # 4. Advance FEFO priority tracker for subsequent batches
                prior_unexpired_cumulative_qty += b_qty

                # 5. Risk Classification
                if unsold_units > 0.01:
                    expiry_status = "EXPIRY_RISK"
                    rec = f"NEAR EXPIRY: Risk of {round(unsold_units, 1)} unsold units. Expedite dispensing or return to vendor."
                else:
                    expiry_status = "HEALTHY_BATCH"
                    rec = "SAFE: Expected demand satisfies batch under standard FEFO dispensing."

            batch_results.append({
                "batch_id": b_id,
                "medicine_id": med,
                "batch_quantity": round(b_qty, 2),
                "expiry_date": exp_date.strftime("%Y-%m-%d"),
                "days_until_expiry": days_until_exp,
                "expected_demand_before_expiry": round(exp_demand_cumulative, 2),
                "prior_batches_quantity": round(prior_qty_deducted, 2),
                "net_demand_allocated": round(net_demand_allocated, 2),
                "unsold_units_at_risk": round(unsold_units, 2),
                "unit_cost": round(cost, 2),
                "value_at_risk": val_at_risk,
                "expiry_status": expiry_status,
                "action_recommendation": rec
            })

    return pd.DataFrame(batch_results)


