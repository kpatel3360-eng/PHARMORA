def calculate_inventory_metrics(
    daily_sales: pd.Series,
    lead_time_days: int = 7,
    service_level_z: float = 1.65  # ~95% service level
) -> Dict[str, float]:
    """
    Computes standard inventory control parameters:
    - Average Daily Demand (d_avg)
    - Demand Standard Deviation (sigma_d)
    - Safety Stock = z * sqrt(lead_time) * sigma_d
    - Reorder Point (ROP) = (d_avg * lead_time) + Safety Stock
    """
    clean_sales = daily_sales.dropna()
    if clean_sales.empty:
        return {
            "avg_daily_demand": 0.0,
            "demand_std": 0.0,
            "safety_stock": 0.0,
            "reorder_point": 0.0,
            "recommended_buffer_days": lead_time_days
        }

    d_avg = float(clean_sales.mean())
    sigma_d = float(clean_sales.std()) if len(clean_sales) > 1 else 0.0

    safety_stock = service_level_z * np.sqrt(lead_time_days) * sigma_d
    reorder_point = (d_avg * lead_time_days) + safety_stock

    return {
        "avg_daily_demand": round(d_avg, 2),
        "demand_std": round(sigma_d, 2),
        "safety_stock": round(safety_stock, 2),
        "reorder_point": round(reorder_point, 2),
        "lead_time_days": lead_time_days
    }


def assess_stock_status(current_stock: float, reorder_point: float, safety_stock: float) -> str:
    """Determines actionable inventory status label for dashboard display."""
    if current_stock <= safety_stock:
        return "CRITICAL - Immediate Reorder Required"
    elif current_stock <= reorder_point:
        return "WARNING - Below Reorder Threshold"
    elif current_stock > (reorder_point * 2.5):
        return "OVERSTOCKED - Review Procurement"
    else:
        return "HEALTHY - Optimal Inventory Buffer"


