# Feature 1: Stockout Risk Detection Engine
# ---------------------------------------------------------------------------
def detect_stockout_risk(
    inventory_df: pd.DataFrame,
    forecast_df: Optional[pd.DataFrame] = None,
    sales_df: Optional[pd.DataFrame] = None
) -> pd.DataFrame:
    """
    Computes stockout risk indicators for warehouse inventory:
    - Inventory Position = Current Stock + Pending Order Quantity
    - Lead-Time Demand = Expected demand during supplier lead time
    - Reorder Point (ROP) = Lead-Time Demand + Safety Stock
    - Days of Stock Cover = Current Stock / Daily Demand (Zero-safe)
    - Risk Classification: CRITICAL_STOCKOUT_RISK, REORDER_WARNING, HEALTHY, OVERSTOCKED
    """
    df = inventory_df.copy()

    # Data sanitization & schema validation
    required_cols = [
        "medicine_id", "current_stock", "supplier_lead_time_days",
        "safety_stock", "pending_order_quantity", "unit_cost"
    ]
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in inventory dataset: {missing_cols}")

    # Coerce numeric types and clip negative quantities
    df["current_stock"] = pd.to_numeric(df["current_stock"], errors="coerce").fillna(0.0).clip(lower=0.0)
    df["pending_order_quantity"] = pd.to_numeric(df["pending_order_quantity"], errors="coerce").fillna(0.0).clip(lower=0.0)
    df["supplier_lead_time_days"] = pd.to_numeric(df["supplier_lead_time_days"], errors="coerce").fillna(7).astype(int).clip(lower=1)
    df["safety_stock"] = pd.to_numeric(df["safety_stock"], errors="coerce").fillna(0.0).clip(lower=0.0)
    df["unit_cost"] = pd.to_numeric(df["unit_cost"], errors="coerce").fillna(0.0).clip(lower=0.0)

    # Filter invalid medicine codes
    df = df[df["medicine_id"].isin(VALID_MEDICINE_IDS)].copy()

    # Precompute historical daily demand averages as fallback
    hist_avg_demand = {}
    if sales_df is not None and not sales_df.empty:
        hist_avg_demand = sales_df.groupby("medicine_id")["units_sold"].mean().to_dict()

    # Organize forecast lookup if provided
    fc_dict = {}
    if forecast_df is not None and not forecast_df.empty:
        fc_clean = forecast_df.copy()
        fc_clean["forecast_date"] = pd.to_datetime(fc_clean["forecast_date"])
        for med, group in fc_clean.groupby("medicine_id"):
            fc_dict[med] = group.sort_values("forecast_date")["predicted_units"].tolist()

    results = []
    for _, row in df.iterrows():
        med = row["medicine_id"]
        stock = float(row["current_stock"])
        pending = float(row["pending_order_quantity"])
        lead_time = int(row["supplier_lead_time_days"])
        ss = float(row["safety_stock"])
        cost = float(row["unit_cost"])

        # 1. Inventory Position
        inv_position = stock + pending

        # 2. Lead-Time Demand (derived from daily forecast or fallback)
        daily_fc = fc_dict.get(med, [])
        hist_mean = hist_avg_demand.get(med, 5.0)

        if daily_fc:
            fc_len = len(daily_fc)
            if lead_time <= fc_len:
                lt_demand = float(sum(daily_fc[:lead_time]))
            else:
                avg_fc = float(np.mean(daily_fc))
                lt_demand = float(sum(daily_fc) + (lead_time - fc_len) * avg_fc)
            daily_rate = float(np.mean(daily_fc))
        else:
            lt_demand = float(lead_time * hist_mean)
            daily_rate = float(hist_mean)

        # 3. Reorder Point (ROP)
        rop = lt_demand + ss

        # 4. Estimated Days of Stock Cover (Zero-Division Safe)
        if daily_rate > 0.0:
            days_cover = round(stock / daily_rate, 1)
        elif stock > 0.0:
            days_cover = 999.0  # Infinite cover if zero demand
        else:
            days_cover = 0.0

        # 5. Risk Status Classification
        if inv_position < lt_demand:
            status = "CRITICAL_STOCKOUT_RISK"
            rec = "IMMEDIATE REORDER: Inventory position cannot fulfill demand during supplier lead time."
        elif inv_position <= rop:
            status = "REORDER_WARNING"
            rec = "REORDER RECOMMENDED: Stock position has reached safety buffer threshold."
        elif inv_position > (2.5 * rop):
            status = "OVERSTOCKED"
            rec = "OVERSTOCKED: Pause procurement; excess capital tied in inventory."
        else:
            status = "HEALTHY"
            rec = "OPTIMAL: Inventory buffer covers lead-time demand with safety reserve."

        inv_value = round(stock * cost, 2)

        results.append({
            "medicine_id": med,
            "current_stock": round(stock, 2),
            "pending_order_quantity": round(pending, 2),
            "inventory_position": round(inv_position, 2),
            "supplier_lead_time_days": lead_time,
            "lead_time_demand": round(lt_demand, 2),
            "safety_stock": round(ss, 2),
            "reorder_point": round(rop, 2),
            "estimated_days_of_cover": days_cover,
            "unit_cost": round(cost, 2),
            "inventory_value": inv_value,
            "risk_status": status,
            "action_recommendation": rec
        })

    return pd.DataFrame(results)


