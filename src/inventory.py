def _read_parquet_or_csv(path: Path) -> pd.DataFrame:
    """Reads a Parquet file/directory or CSV file robustly."""
    if not path.exists():
        raise FileNotFoundError(f"Input file not found at '{path.resolve()}'.")
    if path.suffix == ".csv":
        return pd.read_csv(path)
    if path.is_file():
        return pd.read_parquet(path)
    # Parquet directory with partition files
    parts = [f for f in path.glob("*.parquet") if not f.name.startswith(".")]
    if not parts:
        raise FileNotFoundError(f"No valid Parquet partition files found in directory '{path}'.")
    return pd.concat([pd.read_parquet(f) for f in parts], ignore_index=True)


